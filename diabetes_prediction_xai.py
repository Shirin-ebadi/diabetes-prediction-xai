import os
import pandas as pd
import kagglehub

print("⏳ در حال دانلود خودکار دیتاست معتبر BRFSS2015 از Kaggle...")

# دانلود دیتاست از Kaggle
path = kagglehub.dataset_download("alexteboul/diabetes-health-indicators-dataset")
file_path = os.path.join(path, "diabetes_012_health_indicators_BRFSS2015.csv")

print("📂 در حال خواندن داده‌ها...")
df = pd.read_csv(file_path)
print(f"✅ داده‌ها با موفقیت بارگذاری شدند! ابعاد: {df.shape}")

# ==============================================================================
#  End-to-End Diabetes Prediction Pipeline with SHAP (XAI) & MSE Metrics
# ==============================================================================

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import shap
import warnings

# غیرفعال کردن هشدارهای اضافی
warnings.filterwarnings('ignore')

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, precision_recall_fscore_support, mean_squared_error

# Models
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier, AdaBoostClassifier, GradientBoostingClassifier
from sklearn.svm import LinearSVC
from sklearn.neighbors import KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB

from imblearn.over_sampling import SMOTE
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Dropout, Input
from tensorflow.keras.utils import to_categorical

# ----------------------------------------------------
# ۱. بارگذاری و نمونه‌گیری داده‌ها
# ----------------------------------------------------
print("⚡ [1/4] در حال آماده‌سازی و نمونه‌گیری داده‌ها...")

# استفاده از ۱۵,۰۰۰ نمونه برای حفظ دقت عالی و سرعت بالا
df_sampled = df.sample(n=15000, random_state=42)

X = df_sampled.drop(columns=['Diabetes_012'])
y = df_sampled['Diabetes_012'].astype(int)
feature_names = X.columns.tolist()

# تقسیم داده‌ها به آموزش و تست (جلوگیری از Data Leakage)
X_train_raw, X_test_raw, y_train, y_test = train_test_split(
    X, y, test_size=0.30, stratify=y, random_state=42
)

# نرمال‌سازی داده‌ها
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train_raw)
X_test_scaled = scaler.transform(X_test_raw)

# تبدیل داده‌های تست به DataFrame برای SHAP
X_test_df = pd.DataFrame(X_test_scaled, columns=feature_names)

# رفع عدم تعادل کلاس‌ها با SMOTE (فقط روی داده‌های آموزش)
smote = SMOTE(random_state=42)
X_train_res, y_train_res = smote.fit_resample(X_train_scaled, y_train)

# ----------------------------------------------------
# ۲. آموزش شبکه عصبی (ANN)
# ----------------------------------------------------
print("🚀 [2/4] در حال آموزش شبکه عصبی (ANN)...")
y_train_ann = to_categorical(y_train_res, num_classes=3)

# ساخت مدل با ساختار جدید Input برای حذف Warning
ann_model = Sequential([
    Input(shape=(X_train_res.shape[1],)),
    Dense(32, activation='relu'),
    Dropout(0.2),
    Dense(16, activation='relu'),
    Dense(3, activation='softmax')
])

ann_model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
ann_model.fit(X_train_res, y_train_ann, epochs=8, batch_size=128, verbose=0)

# ----------------------------------------------------
# ۳. آموزش و ارزیابی مدل‌های یادگیری ماشین (به همراه MSE)
# ----------------------------------------------------
print("⚙️ [3/4] در حال آموزش سایر مدل‌ها و ارزیابی...")

ml_models = {
    "Random Forest": RandomForestClassifier(n_estimators=50, max_depth=10, random_state=42, n_jobs=-1),
    "Gradient Boosting": GradientBoostingClassifier(n_estimators=50, random_state=42),
    "Decision Tree": DecisionTreeClassifier(max_depth=10, random_state=42),
    "Logistic Regression": LogisticRegression(max_iter=500, random_state=42),
    "SVM": LinearSVC(random_state=42, dual=False),
    "KNN": KNeighborsClassifier(n_neighbors=5, n_jobs=-1),
    "Naive Bayes": GaussianNB(),
    "AdaBoost": AdaBoostClassifier(n_estimators=50, random_state=42)
}

results_list = []

# ارزیابی ANN
ann_probs = ann_model.predict(X_test_scaled, verbose=0)
ann_preds = np.argmax(ann_probs, axis=1)
acc = accuracy_score(y_test, ann_preds)
mse = mean_squared_error(y_test, ann_preds)
prec, rec, f1, _ = precision_recall_fscore_support(y_test, ann_preds, average='weighted')
results_list.append({
    "Model": "ANN (Proposed)",
    "Accuracy": acc,
    "MSE": mse,
    "Precision": prec,
    "Recall": rec,
    "F1-Score": f1
})

# ارزیابی سایر مدل‌ها
for name, model in ml_models.items():
    model.fit(X_train_res, y_train_res)
    preds = model.predict(X_test_scaled)
    acc = accuracy_score(y_test, preds)
    mse = mean_squared_error(y_test, preds)
    prec, rec, f1, _ = precision_recall_fscore_support(y_test, preds, average='weighted')
    results_list.append({
        "Model": name,
        "Accuracy": acc,
        "MSE": mse,
        "Precision": prec,
        "Recall": rec,
        "F1-Score": f1
    })

# نمایش جدول جامع نتایج
results_df = pd.DataFrame(results_list).sort_values(by="Accuracy", ascending=False)
print("\n" + "="*75)
print("📊 جدول مقایسه عملکرد تمامی مدل‌ها (به همراه MSE):")
print("="*75)
print(results_df.to_string(index=False))

# ----------------------------------------------------
# ۴. تحلیل قابلیت تفسیرپذیری (SHAP XAI)
# ----------------------------------------------------
print("\n💡 [4/4] در حال محاسبه و رسم نمودارهای SHAP...")

best_rf = ml_models["Random Forest"]
explainer = shap.TreeExplainer(best_rf)

# انتخاب ۱۰۰ نمونه جهت پردازش سریع SHAP
X_sample = X_test_df.iloc[:100]
shap_values = explainer(X_sample)

# جداسازی کلاس ۲ (دیابت) برای تحلیل
if len(shap_values.shape) == 3:
    shap_values_class2 = shap_values[:, :, 2]
else:
    shap_values_class2 = shap_values

print("\n📊 ۱. نمودار اهمیت کلی ویژگی‌ها (Bar Plot):")
shap.plots.bar(shap_values_class2)

print("\n📊 ۲. نمودار توزیع تأثیر ویژگی‌ها بر کلاس دیابت (Beeswarm Plot):")
shap.plots.beeswarm(shap_values_class2)